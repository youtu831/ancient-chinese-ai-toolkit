import streamlit as st
col1,col2 = st.columns(2)
# ---------- 零件 1：显示东西 ----------
# st.title 是一个大标题，类似的还有 st.write（万能显示）、st.markdown
with col1:
    st.title("句子改写大测评")
    st.write("帮你改写。")

    # ---------- 零件 2：输入框 ----------
    # st.text_input 画一个输入框，用户输入的内容会装进左边的变量里
    name = st.text_input("要改写的句子：")
    st.write("你刚才输入的是：", name)

with col2:

    # ---------- 零件 3：按钮 ----------
    # st.button 画一个按钮，只有按下时它才是 True
    # 注意：因为脚本会重跑，所以按钮要放在 if 里面判断有没有被按下
    if st.button("开始改写"):
        st.success("你好，" + name + "改写成功。")
        st.balloons()   # 撒个气球庆祝一下
        st.snow()



